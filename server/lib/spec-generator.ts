/**
 * v0.42.0 (AC-4/AC-5) — default cap (in seconds) for the retry-on-429 sleep
 * when `FORGE_SPEC_RETRY_ON_429` is not set. Conservative: 60 seconds leaves
 * headroom under common operator-configured MCP tool-call timeouts (typically
 * 30-120s). Operators with tighter limits override via env. Setting
 * `FORGE_SPEC_RETRY_ON_429=0` disables retry entirely. Plan §AC-4.
 */
const RETRY_ON_429_DEFAULT_SEC = 60;

/**
 * v0.42.0 (AC-3) — sleep helper backing the retry-on-429 wrapper. Exported
 * via the `sleepFn` P64 injection seam on `SpecGeneratorInput` so vitest can
 * stub without burning real wall-clock. Default = `setTimeout`-backed promise.
 */
function defaultSleep(ms: number): Promise<void> {
  return new Promise((resolve) => setTimeout(resolve, ms));
}

/**
 * v0.42.0 (AC-4) — parse the `FORGE_SPEC_RETRY_ON_429` env var. Returns the
 * configured cap in SECONDS, or the default (60) when unset / malformed.
 * `0` is a legitimate "retry disabled" value and propagates through.
 * Negative or non-numeric values fall back to the default per F46
 * (no-silent-numeric-default — we warn-and-default rather than crash because
 * the spec-generator is on the PASS hot path; an env var typo must not nuke
 * a story's verdict, just disable the retry behaviour and log the misuse).
 */
function parseRetryOn429Cap(raw: string | undefined): number {
  if (raw === undefined || raw === "") return RETRY_ON_429_DEFAULT_SEC;
  const trimmed = raw.trim();
  if (!/^\d+$/.test(trimmed)) {
    console.error(
      `spec-generator: ignoring malformed FORGE_SPEC_RETRY_ON_429="${raw}" (expected non-negative integer seconds); using default ${RETRY_ON_429_DEFAULT_SEC}s`,
    );
    return RETRY_ON_429_DEFAULT_SEC;
  }
  return Number.parseInt(trimmed, 10);
}

/**
 * Agent-first header (Bundle 1a). Five HTML-comment lines + 1 blank line are
 * BYTE-IDENTICAL across regenerations (idempotency contract AC-1a-3). The
 * visible "Generated by ..." date line that follows refreshes on every call
 * and is excluded from idempotency checks. Together they satisfy AC-1a-2.
 */
const AGENT_FIRST_COMMENT_BLOCK = [
  "<!-- agent-first: this file is auto-regenerated by forge-harness on every story PASS. -->",
  "<!-- Source of truth: docs/decisions/<US-NN>/*.md (ADRs) and docs/generated/<US-NN>.md (TECHNICAL-SPEC). -->",
  "<!-- Do not hand-edit; edits are overwritten on next regeneration. -->",
  "<!-- Regeneration tool: forge-harness `forge_evaluate` (PASS verdict path). -->",
  "<!-- Design rationale: P60 Build for Consumer, Not Author. -->",
];

/**
 * Match the leading agent-first header (5 HTML comments + blank line + visible
 * "Generated by ..." line + blank line). Used by `parseSpec` to skip the header
 * before locating the YAML front-matter fence.
 */
const AGENT_FIRST_HEADER_RE =
  /^(?:<!--[^\n]*-->\n){5}\n> Generated by forge-harness on \d{4}-\d{2}-\d{2}\.\n\n/;

