/**
 * Generate or update a story's section in `docs/generated/TECHNICAL-SPEC.md`.
 * Idempotent across re-runs: same story id always produces exactly one
 * `## story: <id>` heading in the body and exactly one entry in the
 * front-matter `stories[]` array.
 *
 * Returns metadata for the caller to stamp into `RunRecord.generatedDocs`.
 */
export async function generateSpecForStory(
  input: SpecGeneratorInput,
): Promise<SpecGeneratorResult> {
  const specPath = resolve(input.projectPath, SPEC_REL_PATH);
  const now = new Date().toISOString();
  const gitShaSafe = input.gitSha && /^[0-9a-f]{40}$/.test(input.gitSha)
    ? input.gitSha
    : "unknown";

  // Read existing spec (or scaffold an empty one).
  let parsed: ParsedSpec;
  if (existsSync(specPath)) {
    const text = readFileSync(specPath, "utf-8");
    try {
      parsed = parseSpec(text);
    } catch (err) {
      // Corrupted file — start fresh, but log the cause so the operator can
      // recover the prior content from git.
      console.error(
        `spec-generator: existing spec at ${specPath} is malformed (${err instanceof Error ? err.message : String(err)}); rewriting from scratch`,
      );
      parsed = emptySpec(now);
    }
  } else {
    parsed = emptySpec(now);
  }

  // Build source vocabulary from the story's affectedPaths. Empty/omitted
  // paths fall back to the "No source vocabulary available" prompt.
  const vocab = buildSourceVocabulary(
    input.projectPath,
    input.affectedPaths ?? [],
  );
  const vocabularyPrompt = renderVocabularyForPrompt(vocab);

  // Synthesise the new section.
  // I6 — single-locus try/catch around `synth()`. When the LLM call fails
  // (auth/network/parse/zod after I8's retry exhausted), fall back to a
  // byte-stable placeholder body so the rest of `generateSpecForStory`
  // (vocab merge, frontmatter `lastUpdated` refresh, section merge,
  // `idempotentWrite`) still runs and the spec file is partially regenerated.
  // The structural fields refresh deterministically; only the prose body is
  // a placeholder until LLM creds return. Mint locus locked here per F49 —
  // the F4 catch in `evaluate.ts` continues to handle truly-non-recoverable
  // throws (e.g. the placeholder write itself fails); see plan §59.
  const synth = input.synthesize ?? ((req) => defaultSynthesize(input.ctx, req));
  const sleep = input.sleepFn ?? defaultSleep;
  const diffSummary = captureDiffSummary(input.projectPath);
  // v0.42.0 (AC-4) — retry cap is read PER CALL (not module-load) so vitest
  // can mutate `process.env.FORGE_SPEC_RETRY_ON_429` between tests.
  const retryOn429Cap = parseRetryOn429Cap(process.env.FORGE_SPEC_RETRY_ON_429);
  // Initialise to a safe shape so the type-checker can prove definite
  // assignment after the retry loop. The shell-only path overwrites this
  // with placeholder bodies; the success path overwrites via the loop's
  // try-block. The initialiser is never observed by downstream code.
  let synthResult: SynthesisResponse = {
    contracts: [],
    sections: {
      "api-contracts": "(none)",
      "data-models": "(none)",
      invariants: "(none)",
      "test-surface": "(none)",
    },
    tokens: { inputTokens: 0, outputTokens: 0 },
  };
  let shellOnly = false;
  let shellOnlyMessage = "";
  // v0.42.0 (AC-1b) — set when synth() RESOLVED successfully but produced
  // empty / all-`(none)` sections (LLM 200 OK with no usable content). The
  // file write is skipped just like the throw path so existing content is
  // preserved.
  let emptySections = false;
  // v0.42.0 (AC-3) — retry-on-429 wrapper. One retry attempt max, gated by
  // `FORGE_SPEC_RETRY_ON_429` (0 = disabled, default 60s cap, cap-clamped).
  // SDK's `maxRetries: 0` (set in anthropic.ts) means this is THE only retry
  // layer — no SDK double-up.
  let synthThrew = false;
  let synthError: unknown = undefined;
  for (let attempt = 0; attempt < 2; attempt++) {
    try {
      synthResult = await synth({
        storyId: input.storyId,
        evalReport: input.evalReport,
        diffSummary,
        vocabularyPrompt,
      });
      synthThrew = false;
      synthError = undefined;
      break;
    } catch (err) {
      synthThrew = true;
      synthError = err;
      // Retry conditions: cap > 0 AND this is the first attempt AND error
      // is a 429 RateLimitError. Everything else falls through to the
      // existing catch handling (AC-3b: retry-exhaustion → no-overwrite).
      const isRateLimit = err instanceof Anthropic.RateLimitError;
      if (retryOn429Cap > 0 && attempt === 0 && isRateLimit) {
        const retryAfterHeader = err.headers?.get("retry-after");
        const retryAfterSeconds = retryAfterHeader
          ? Number.parseInt(retryAfterHeader, 10)
          : 0;
        // AC-5 — clamp to cap. Default 1s when header is missing / unparseable
        // so a header-less 429 still backs off briefly rather than hammering.
        const requestedSec =
          Number.isFinite(retryAfterSeconds) && retryAfterSeconds > 0
            ? retryAfterSeconds
            : 1;
        const sleepSec = Math.min(requestedSec, retryOn429Cap);
        await sleep(sleepSec * 1000);
        continue;
      }
      break;
    }
  }
  // After the retry loop: if synth succeeded, synthResult is set and
  // synthThrew=false. If it failed (initial throw + no retry, or
  // retry-exhausted), fall into the existing catch logic below.
  if (synthThrew) {
    const err = synthError;
    shellOnly = true;
    let raw = err instanceof Error ? err.message : String(err);

    // #548 (v0.40.7) — surface Anthropic's `retry-after` header on 429 so
    // operators know when it's safe to retry. The SDK exposes `RateLimitError`
    // (extends APIError<429, Headers>) with a `Headers` Web-API instance —
    // accessor is `.get('retry-after')` (NOT bracket-index — Headers is a
    // class, not a record).
    //
    // The header value per RFC 7231 §7.1.3 is either:
    //   - integer seconds (most common — Anthropic returns this shape)
    //   - HTTP-date (RFC 1123) — fallback parse
    //
    // We append the parsed/raw value to `raw` BEFORE the truncation step
    // so the suffix lives inside the warning's visible window.
    if (err instanceof Anthropic.RateLimitError) {
      const retryAfter = err.headers?.get("retry-after");
      if (retryAfter) {
        const seconds = Number.parseInt(retryAfter, 10);
        const suffix = Number.isFinite(seconds) && seconds > 0
          ? ` (retry after ${seconds}s)`
          : ` (retry after ${retryAfter})`;
        raw = `${raw}${suffix}`;
      }
    }

    shellOnlyMessage =
      raw.length > SHELL_ONLY_MESSAGE_MAX
        ? raw.slice(0, SHELL_ONLY_MESSAGE_MAX) + "…(truncated)"
        : raw;
    console.error(
      `spec-generator: synth() failed (continuing with shell-only placeholder body): ${raw}`,
    );
    synthResult = {
      contracts: [],
      sections: {
        "api-contracts": SHELL_ONLY_PLACEHOLDER_BODY,
        "data-models": SHELL_ONLY_PLACEHOLDER_BODY,
        invariants: SHELL_ONLY_PLACEHOLDER_BODY,
        "test-surface": SHELL_ONLY_PLACEHOLDER_BODY,
      },
      tokens: { inputTokens: 0, outputTokens: 0 },
    };
  } else {
    // v0.42.0 (AC-1b) — empty-sections detection on the success path. If the
    // LLM returned 200 OK but `defaultSynthesize` defaulted EVERY section to
    // `"(none)"` (because parsed.sections was empty / malformed / all-empty
    // strings), the spec-generator MUST NOT overwrite existing TECHNICAL-SPEC
    // content with `(none)` lines. The synth call succeeded but produced
    // nothing usable; treat that as a soft failure that preserves prior content.
    //
    // Distinguished from the LEGIT case where the LLM intentionally emits
    // `(none)` for ONE section but real content for the other three — that
    // flows through normally and DOES overwrite. The discriminator: ALL FOUR
    // sections are exactly `"(none)"` (case-sensitive).
    const allNone = REQUIRED_SECTIONS.every(
      (k) => (synthResult!.sections[k] ?? "").trim() === "(none)",
    );
    if (allNone) {
      emptySections = true;
    }
  }

  // Strategy 2: post-validate against the vocabulary. Strips bullets whose
  // backtick-quoted identifiers are not present in vocab (mode=strip), or
  // logs warnings without stripping (mode=warn). Skip entirely when the
  // vocabulary is empty (no source files to ground on) — every bullet would
  // be a false positive.
  let validatedSections = synthResult.sections;
  let warnings: SpecGeneratorWarning[] = [];
  const hasVocab = vocab.identifiers.size > 0 || vocab.testNames.size > 0;
  if (hasVocab) {
    const validated = validateAgainstVocabulary(
      synthResult.sections,
      vocab,
      { filesScanned: vocab.filesScanned.length },
    );
    validatedSections = validated.sections;
    warnings = validated.warnings;
  } else {
    // AC-8 lenient mode: no source vocabulary to ground on. Spec writes
    // verbatim (no strips). Emit one informational warning so consumers can
    // tell "validator skipped" apart from "validator ran clean".
    warnings = [{ kind: "no-vocabulary", filesScanned: vocab.filesScanned.length }];
  }

  // I6 — append the `spec-gen-shell-only` warning when `synth()` threw. Same
  // emit point as `no-vocabulary` (validator-pass site) per the plan; this is
  // additive and orthogonal to existing warnings (e.g. when `no-vocabulary`
  // already fired because there was no source vocab to ground on, the
  // shell-only marker still belongs in the array — both signals are true).
  if (shellOnly) {
    warnings.push({ kind: "spec-gen-shell-only", message: shellOnlyMessage });

    // F6 (v0.40.5) — macOS-only diagnostic. When the run fell through to
    // shell-only on darwin, do a cheap exit-code-only probe of macOS
    // Keychain to distinguish "no creds at all" from "creds exist in
    // Keychain but forge can't read them" (locked, prompt-timeout, ACL
    // mismatch). The latter case gets a typed `spec-gen-creds-keychain-only`
    // warning telling the operator to set ANTHROPIC_API_KEY to bypass
    // (rather than the misleading "log in to Claude Code" advice — they
    // already are).
    //
    // Single-locus per F49: KEYCHAIN_SERVICE_NAME is imported from
    // anthropic.ts (the OAuth read locus) so the service-name string lives
    // at one source-of-truth.
    //
    // F45 escape: if the existence-probe ITSELF throws unexpectedly (not
    // just non-zero exit — e.g. /usr/bin/security missing on a stripped-down
    // macOS install), fall through to emitting only `spec-gen-shell-only`.
    // Loud failure preserved via the existing shell-only warning.
    //
    // #546 (v0.40.7) — narrowing gate. The keychain warning is meaningful
    // ONLY when the underlying synth() failure was auth-class. If the
    // failure was an HTTP 4xx (other than 401) or 5xx — e.g. 429 rate-limit,
    // 500 server error — credentials are FINE; the keychain probe would
    // emit a misleading "Keychain locked or ACL mismatched" warning that
    // sends the operator down the wrong diagnostic path.
    //
    // Anthropic SDK's `APIError.makeMessage` (verified at
    // node_modules/@anthropic-ai/sdk/core/error.js:18-29) returns
    // `${status} ${msg}` when both status and msg are truthy — so a real
    // 429 produces `err.message = "429 ..."`. The regex `^[45][0-9]{2}\b`
    // matches HTTP 4xx/5xx prefix (P64 producer/consumer seam asserted in
    // tests, F65 measurement-discipline grounded against the SDK source).
    //
    // 401 (AuthenticationError) is excluded from suppression because it IS
    // auth-class — the keychain probe IS meaningful for 401. The regex
    // matches all 4xx/5xx including 401, so we explicitly carve 401 out
    // below to preserve the original F6 path.
    const isHttp4xxOr5xx = /^[45][0-9]{2}\b/.test(shellOnlyMessage);
    const is401 = /^401\b/.test(shellOnlyMessage);
    const suppressKeychainProbe = isHttp4xxOr5xx && !is401;
    if (process.platform === "darwin" && !suppressKeychainProbe) {
      let keychainEntryExists = false;
      // #546 / v0.41.1 — P64 injection seam. Default to real execFileSync;
      // tests pass `input.execFileSyncFn` to deterministically simulate
      // entry-exists (success return) or entry-absent (throw).
      const execFile = input.execFileSyncFn ?? execFileSync;
      try {
        execFile(
          "/usr/bin/security",
          ["find-generic-password", "-s", KEYCHAIN_SERVICE_NAME, "-a", userInfo().username],
          { stdio: "ignore", timeout: 1000 },
        );
        // Exit 0 → entry exists. Our reader couldn't get a usable token
        // from it (else we wouldn't be in shellOnly), so creds are
        // present-but-unreadable.
        keychainEntryExists = true;
      } catch {
        // Non-zero exit OR probe itself threw → entry truly missing or
        // unprobable. Emit only spec-gen-shell-only (existing behavior).
      }
      if (keychainEntryExists) {
        warnings.push({
          kind: "spec-gen-creds-keychain-only",
          message:
            `macOS Keychain entry exists for "${KEYCHAIN_SERVICE_NAME}" but forge-harness ` +
            `could not read it (locked, prompt-timeout, or ACL mismatch). ` +
            `Set ANTHROPIC_API_KEY to bypass.`,
        });
      }
    }
  }

  // v0.42.0 (AC-1b) — emit `spec-gen-empty-sections` warning when synth
  // succeeded but produced no usable content. Companion to the no-write gate
  // below; this is the loud-failure surface so consumers see WHY the file
  // wasn't refreshed.
  if (emptySections) {
    warnings.push({
      kind: "spec-gen-empty-sections",
      message:
        "synth() resolved with empty / all-(none) sections; existing TECHNICAL-SPEC content preserved",
    });
  }

  // v0.42.0 (AC-1 / AC-1b / P34 Strict Output Contract) — when synth failed
  // OR returned empty sections, SKIP the merge + write entirely. Existing
  // content is preserved; warnings already surface the cause. Loud failure
  // (warnings) is always better than silent corruption (placeholder
  // overwrite). The pre-v0.42.0 path overwrote real content with
  // `SHELL_ONLY_PLACEHOLDER_BODY` and was the silent-data-loss bug fixed
  // here. Cairn-stone: F-FORGE-SPEC-GEN-OVERWRITES-ON-SYNTH-FAILURE.
  const preserveExistingOnSynthFailure = shellOnly || emptySections;
  if (preserveExistingOnSynthFailure) {
    return {
      specPath,
      genTimestamp: now,
      genTokens: synthResult.tokens,
      contracts: synthResult.contracts,
      bodyChanged: false,
      warnings,
    };
  }

  // Merge into front-matter `stories[]` by id.
  const idx = parsed.frontMatter.stories.findIndex((s) => s.id === input.storyId);
  const entry = { id: input.storyId, lastUpdated: now, lastGitSha: gitShaSafe };
  if (idx === -1) parsed.frontMatter.stories.push(entry);
  else parsed.frontMatter.stories[idx] = entry;
  // Sort by id for byte-stable output.
  parsed.frontMatter.stories.sort((a, b) => a.id.localeCompare(b.id));
  parsed.frontMatter.lastUpdated = now;
  parsed.frontMatter.schemaVersion = SCHEMA_VERSION;

  // Rebuild body: replace any existing `## story: <id>` block, otherwise
  // append. The current body may contain multiple sections; we walk them.
  const newSection = renderStorySection(input.storyId, validatedSections);
  const bodyChanged = mergeStorySectionInBody(parsed, input.storyId, newSection);

  // Write atomically. Prepend the Bundle 1a agent-first header (5 HTML
  // comments + blank line) and the visible "Generated by ..." line so any
  // agent who opens the file sees its purpose, regeneration policy, and
  // last-refresh date in the first 7 lines. The date line uses today's
  // calendar date (UTC); the comment block is byte-identical across regens
  // per AC-1a-3.
  mkdirSync(dirname(specPath), { recursive: true });
  const today = now.slice(0, 10);
  const headerBlock = [
    ...AGENT_FIRST_COMMENT_BLOCK,
    "",
    `> Generated by forge-harness on ${today}.`,
    "",
  ].join("\n");
  const out = `${headerBlock}\n---\n${renderFrontMatter(parsed.frontMatter)}\n---\n\n${normaliseBody(parsed.body)}`;
  // W3 (#514): skip the write if the existing file already represents the
  // same logical state (ignoring the daily date line and the `lastUpdated:`
  // timestamps). Eliminates per-PASS dated-banner churn in consumer repos.
  // Preserves AC-1a-3 byte-stability of the agent-first comment block.
  idempotentWrite(specPath, out);

  return {
    specPath,
    genTimestamp: now,
    genTokens: synthResult.tokens,
    contracts: synthResult.contracts,
    bodyChanged,
    warnings,
  };
}

function emptySpec(timestamp: string): ParsedSpec {
  return {
    frontMatter: {
      schemaVersion: SCHEMA_VERSION,
      lastUpdated: timestamp,
      stories: [],
    },
    body: "",
  };
}

/**
 * In-place: replace or append the `## story: <id>` block in `parsed.body`.
 * Returns true if a textually different block was written (a write that only
 * updates `lastUpdated` may still produce identical body; the front-matter
 * mutation is what the spec sees in that case).
 */
function mergeStorySectionInBody(
  parsed: ParsedSpec,
  storyId: string,
  newSection: string,
): boolean {
  const sections = splitBodyByStory(parsed.body);
  let replaced = false;
  let bodyChanged = false;
  const merged: string[] = [];
  for (const s of sections) {
    if (s.id === storyId) {
      if (s.markdown.trim() !== newSection.trim()) bodyChanged = true;
      merged.push(newSection);
      replaced = true;
    } else {
      merged.push(s.markdown);
    }
  }
  if (!replaced) {
    merged.push(newSection);
    bodyChanged = true;
  }
  // Sort the story sections by id for byte-stable output, preserving any
  // free-floating non-story `## ...` blocks at the top.
  const storyChunks = merged.filter((m) => /^## story: /.test(m));
  const otherChunks = merged.filter((m) => !/^## story: /.test(m));
  storyChunks.sort((a, b) => {
    const aId = a.match(/^## story: (\S.*)/)?.[1] ?? "";
    const bId = b.match(/^## story: (\S.*)/)?.[1] ?? "";
    return aId.localeCompare(bId);
  });
  // W4 (#515): trim ALL trailing whitespace (newlines and spaces) from each
  // chunk before joining so the `"\n\n"` join produces exactly one blank line
  // between adjacent sections — never two or three. Without this, sections
  // that already ended with a trailing blank line stack with the join's two
  // newlines to produce `\n\n\n` (a triple-blank-line gap), and re-rendering
  // a story section perturbs the bytes of OTHER (unrelated) story sections.
  const trim = (chunk: string) => chunk.replace(/\s+$/, "");
  parsed.body = [...otherChunks, ...storyChunks].map(trim).join("\n\n").trim();
  return bodyChanged;
}

function normaliseBody(body: string): string {
  return body.replace(/\r\n/g, "\n").trim() + "\n";
}
